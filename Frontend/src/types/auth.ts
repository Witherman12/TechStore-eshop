export interface AuthUser {
  userId: string;
  username: string;
  email: string;
  role: string;
}

export interface LoginRequest {
  username: string;
  password: string;
}

export interface RegisterRequest {
  username: string;
  email: string;
  password: string;
}

export interface AuthResponse extends AuthUser {
  token: string;
  expiresAt: string;
}